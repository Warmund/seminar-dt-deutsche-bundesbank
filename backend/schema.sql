CREATE TABLE IF NOT EXISTS moneta_records (
    dataset_id bigint NOT NULL DEFAULT 1 REFERENCES moneta_datasets(id),
    osm_type text NOT NULL CHECK (osm_type IN ('node', 'way', 'relation')),
    osm_id bigint NOT NULL,
    name text NOT NULL,
    category text NOT NULL,
    data jsonb NOT NULL,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dataset_id, osm_type, osm_id)
);
CREATE TABLE IF NOT EXISTS moneta_images (
    dataset_id bigint NOT NULL DEFAULT 1 REFERENCES moneta_datasets(id),
    osm_type text NOT NULL,
    osm_id bigint NOT NULL,
    kind text NOT NULL CHECK (kind IN ('osm', 'satellite')),
    content bytea CHECK (octet_length(content) <= 3000000),
    object_key text,
    updated_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (dataset_id, osm_type, osm_id, kind),
    FOREIGN KEY (dataset_id, osm_type, osm_id) REFERENCES moneta_records(dataset_id, osm_type, osm_id) ON DELETE CASCADE
);

